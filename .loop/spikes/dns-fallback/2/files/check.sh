#!/usr/bin/env bash
# Read-only spike for dns-fallback R1. Changes nothing on the nodes: reads man
# pages and config, and parses a copy of the config under /tmp/nmspike with
# `NetworkManager --print-config`, which prints the merged config and exits.
# Exits 0 only when both nodes document and parse [global-dns] servers/options
# and NetworkManager itself writes /etc/resolv.conf.
set -u
KEY=/home/vscode/workspace/.ssh/id_rsa
fail=0

remote() {
cat <<'EOF'
set -u
echo "--- version"; NetworkManager --version
echo "--- man NetworkManager.conf: reload, global-dns"
M=$(MANWIDTH=100 man -P cat NetworkManager.conf 2>/dev/null)
echo "$M" | grep -n -B1 -A2 -iE 'SIGHUP|reloaded at runtime'
echo "$M" | awk '/^GLOBAL-DNS SECTION/{p=1} /^(\.CONFIG SECTIONS|CONNECTION SECTION|PLUGINS|APPENDIX)/{p=0} p'
echo "--- man nmcli: general reload"
MANWIDTH=100 man -P cat nmcli 2>/dev/null | grep -n -A22 -E '^ +reload \['
echo "--- live config (dns, rc-manager)"
NetworkManager --print-config 2>&1 | grep -E '^\[main\]|^#? *(dns|rc-manager|systemd-resolved)='
echo "--- /etc/resolv.conf"; ls -l /etc/resolv.conf; cat /etc/resolv.conf
echo "--- conf.d"; ls -la /etc/NetworkManager/conf.d/ 2>&1; for f in /etc/NetworkManager/conf.d/*.conf; do echo "# $f"; cat "$f"; done; echo "--- resolved"; systemctl is-active systemd-resolved 2>&1
echo "--- parse test"
rm -rf /tmp/nmspike; mkdir -p /tmp/nmspike/conf.d /tmp/nmspike/sys
cp /etc/NetworkManager/NetworkManager.conf /tmp/nmspike/NetworkManager.conf
cp -a /etc/NetworkManager/conf.d/. /tmp/nmspike/conf.d/ 2>/dev/null
cat > /tmp/nmspike/conf.d/90-dns-fallback.conf <<'CONF'
[global-dns]
options=timeout:1,attempts:2

[global-dns-domain-*]
servers=192.168.2.254,1.1.1.1,9.9.9.9
CONF
NetworkManager --print-config \
  --config=/tmp/nmspike/NetworkManager.conf \
  --config-dir=/tmp/nmspike/conf.d \
  --intern-config=/tmp/nmspike/intern.conf 2>&1 \
  | awk '/^\[/{p=($0 ~ /^\[(main|global-dns)/)} p'
echo "--- parse exit $?"
rm -rf /tmp/nmspike
EOF
}

for h in radxa@192.168.2.50 orangepi@192.168.2.29; do
  echo "===== $h"
  out=$(remote | ssh -i "$KEY" -o BatchMode=yes -o ConnectTimeout=10 "$h" bash -s)
  echo "$out"
  parsed=$(echo "$out" | sed -n '/^--- parse test/,$p')
  check() { if echo "$2" | grep -qE "$3"; then echo "PASS $h: $1"; else echo "FAIL $h: $1"; fail=1; fi; }
  check "man documents global-dns options" "$out" '^GLOBAL-DNS SECTION'
  check "man documents global-dns-domain servers" "$out" '^ +servers$'
  check "man says global-dns overrides connection DNS" "$out" 'override connection-specific|override the ones from active connections'
  check "merged config has [global-dns] options" "$parsed" '^options=timeout:1,attempts:2'
  check "merged config has [global-dns-domain-*] servers" "$parsed" '^\[global-dns-domain-\*\]'
  check "merged servers list" "$parsed" '^servers=192\.168\.2\.254,1\.1\.1\.1,9\.9\.9\.9'
  check "resolv.conf generated by NetworkManager" "$out" '^# Generated by NetworkManager'
done
exit $fail
